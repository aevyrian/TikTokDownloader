import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),{profileCount}=require('../userscripts/douyin-send.user.js');
const author='https://www.douyin.com/user/MS4wLjABAAAA_test_author';
const data=count=>({statusCode:0,user:{secUid:'MS4wLjABAAAA_test_author',awemeCount:count}});
const script=value=>`self.__pace_f.push(${JSON.stringify([1,'8:'+JSON.stringify(['$','$Lprofile',null,{uid:'MS4wLjABAAAA_test_author',statusCode:0,post:{},user:value}])+'\n'])})`;
for(const count of [0,47,123456])assert.equal(profileCount([script(data(count))],author),count);
for(const count of [undefined,null,'47',-1,1.5,Number.MAX_SAFE_INTEGER+1])assert.equal(profileCount([script(data(count))],author),null);
assert.equal(profileCount([script({...data(47),statusCode:1})],author),null);
assert.equal(profileCount([script({...data(47),statusCode:false})],author),null);
const other=script({statusCode:0,user:{secUid:'MS4wLjABAAAA_someone_else',awemeCount:999}});
assert.equal(profileCount([other,script(data(47))],author),47,'不能误读页面中的登录用户或推荐作者');
assert.equal(profileCount([other],author),null);
const nonProfile=`self.__pace_f.push(${JSON.stringify([1,'7:'+JSON.stringify(['$','$Lother',null,{user:data(0)}])])})`;
assert.equal(profileCount([nonProfile,script(data(105))],author),105,'同一作者的其他组件默认值不能冒充主页资料');
assert.equal(profileCount(['self.__pace_f.push([1,"8:{broken"]);',script(data(47))],author),47,'忽略无关或损坏的数据块');
assert.equal(profileCount(['window.codeMustNotRun=true;'],author),null,'不执行页面脚本');
assert.equal(profileCount([],author),null);
assert.equal(profileCount([script(data(47))],'https://evil.test/user/MS4wLjABAAAA_test_author'),null);
